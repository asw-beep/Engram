"""Build docs/phase-2-evaluation.md from the result files eval.run wrote.

    uv run python -m eval.report

Every number in the document comes from a result file. A configuration without one is
listed as "not run", never estimated (CLAUDE.md, "Evaluation claims").
"""

import argparse
import json
import re
from collections import Counter
from pathlib import Path

from eval.dataset import KINDS, Question, load_questions
from eval.metrics import Ranked, exact_mcnemar, recall_at

CONFIGS = ("dense", "hybrid", "dense_rerank", "hybrid_rerank")
DESCRIPTIONS = {
    "dense": "BGE-M3 vectors in Qdrant",
    "hybrid": "dense and BM25 (OpenSearch), fused with RRF",
    "dense_rerank": "dense, then BGE-reranker-v2-m3",
    "hybrid_rerank": "hybrid, then BGE-reranker-v2-m3",
}
# Each pair isolates one change: OpenSearch alone, the reranker alone, both, and OpenSearch
# once the reranker is there.
PAIRS = (
    ("hybrid", "dense"),
    ("dense_rerank", "dense"),
    ("hybrid_rerank", "dense"),
    ("hybrid_rerank", "dense_rerank"),
)
VERDICTS = ("supports", "partly", "does not support")
# How an answer names a passage instead of citing it with a marker such as [1].
PASSAGE_NAMED = re.compile(
    r"\bpassages?\s+\d+|\bthe\s+(?:first|second|third|fourth|fifth|last|next|previous)\s+"
    r"passage",
    re.IGNORECASE,
)
RECALL_TARGET = 0.85
LATENCY_TARGET_MS = 5000


def render(
    results: dict[str, dict],
    questions: list[Question],
    reviewed: bool,
    calibration: dict[str, dict] | None = None,
    answer_review: dict | None = None,
) -> str:
    parts = [_heading(reviewed), _dataset(results, questions), _quality(results)]
    parts += [_by_kind(results, questions), _gate(results, calibration or {})]
    parts += [_paired(results, questions), _latency(results), _answer_review(answer_review)]
    parts += [_targets(results, reviewed), _limits(questions, reviewed)]
    return "\n\n".join(parts) + "\n"


def _heading(reviewed: bool) -> str:
    status = (
        "**Status: reviewed.** The owner has reviewed a sample of the questions and their gold "
        "labels (`backend/eval/review.json`)."
        if reviewed
        else "**Status: Provisional.** The owner hasn't reviewed the sample of questions and "
        "gold labels yet, so no number here counts as a result (spec §3)."
    )
    return (
        "# Phase 2 retrieval evaluation\n\n"
        f"{status}\n\n"
        "Generated by `uv run python -m eval.report` from `backend/eval/results/*.json`. "
        "Regenerate it rather than editing it. Each configuration's numbers come from "
        "`uv run python -m eval.run --config <name>`, run from `backend/`."
    )


def _dataset(results: dict[str, dict], questions: list[Question]) -> str:
    counts = Counter((q.kind, q.split) for q in questions)
    rows = [
        f"| {kind} | {counts[kind, 'dev']} | {counts[kind, 'test']} |"
        for kind in KINDS
        if counts[kind, "dev"] or counts[kind, "test"]
    ]
    corpora = {config: r["corpus"] for config, r in results.items() if "corpus" in r}
    corpus = next(iter(corpora.values()), None)
    corpus_line = (
        f"The corpus held {corpus['documents']} current documents and {corpus['chunks']} chunks "
        "when the first listed run was made."
        if corpus
        else "No run has been made, so the corpus size isn't recorded."
    )
    if any(other != corpus for other in corpora.values()):
        sizes = ", ".join(
            f"{config} {c['documents']} documents and {c['chunks']} chunks"
            for config, c in corpora.items()
        )
        corpus_line += (
            f" **Warning:** the runs were made on different corpora ({sizes}), so their "
            "numbers can't be compared. Rerun them on one corpus."
        )
    return (
        "## Dataset\n\n"
        f"{len(questions)} questions, written for this project by its author from the corpus "
        "and not collected from real users. `backend/eval/README.md` describes the corpus, "
        "its commit, how the questions were written and the split rule. Tuning uses the `dev` "
        "split only; every number below is from the `test` split.\n\n"
        "| Kind | dev | test |\n|---|---:|---:|\n" + "\n".join(rows) + f"\n\n{corpus_line}"
    )


def _quality(results: dict[str, dict]) -> str:
    rows = []
    for config in CONFIGS:
        overall = _summary(results, config).get("overall")
        if config not in results:
            rows.append(f"| {config} | not run | – | – | – |")
        else:
            metrics = ("recall@5", "recall@10", "mrr@10", "ndcg@10")
            rows.append(f"| {config} | " + " | ".join(_num(overall, m) for m in metrics) + " |")
    legend = "\n".join(f"- `{c}`: {DESCRIPTIONS[c]}" for c in CONFIGS)
    return (
        "## Retrieval quality (test split, answerable questions)\n\n"
        "| Configuration | Recall@5 | Recall@10 | MRR@10 | NDCG@10 |\n"
        "|---|---:|---:|---:|---:|\n" + "\n".join(rows) + "\n\n" + legend + "\n\n"
        "A chunk is relevant when it comes from a gold document and its heading path starts "
        "with a gold section's. Recall@K counts a question only when every gold section has a "
        "chunk in the top K, so a `multi_section` question needs both. NDCG is graded: the "
        "first chunk from each gold section earns 2 and the first chunk from elsewhere in a "
        "gold document earns 1, so a ranking holding only the gold sections scores below 1 "
        "when the rest of a gold document could also have been found."
    )


def _by_kind(results: dict[str, dict], questions: list[Question]) -> str:
    tested = Counter(q.kind for q in questions if q.split == "test" and q.kind != "unanswerable")
    rows = []
    for kind in KINDS:
        if not tested[kind]:
            continue
        cells = []
        for config in CONFIGS:
            stats = (_summary(results, config).get("by_kind") or {}).get(kind)
            if config not in results:
                cells.append("not run")
            else:
                cells.append(f"{_num(stats, 'recall@5')} / {_num(stats, 'mrr@10')}")
        rows.append(f"| {kind} | {tested[kind]} | " + " | ".join(cells) + " |")
    return (
        "## By question kind (test split, Recall@5 / MRR@10)\n\n"
        "| Kind | Questions | "
        + " | ".join(CONFIGS)
        + " |\n|---|---:|"
        + "---|" * len(CONFIGS)
        + "\n"
        + "\n".join(rows)
    )


def _gate(results: dict[str, dict], calibration: dict[str, dict]) -> str:
    rows = []
    for config in CONFIGS:
        gate = _summary(results, config).get("evidence_gate")
        if config not in results:
            rows.append(f"| {config} | not run | – | – | – | – |")
        else:
            source = results[config].get("cutoff_from", "not recorded")
            if gate is None:
                rows.append(f"| {config} | – | {source} | – | – | – |")
                continue
            cells = [_num(gate, key) for key in ("answerable_passed", "unanswerable_refused")]
            rows.append(
                f"| {config} | {_num(gate, 'cutoff')} | {source} | "
                + " | ".join(cells)
                + f" | {_num(gate, 'balanced_accuracy')} |"
            )
    return (
        "## Evidence gate (test split)\n\n"
        "| Configuration | Cutoff | Cutoff from | Answerable passed | Unanswerable refused | "
        "Balanced accuracy |\n|---|---:|---|---:|---:|---:|\n" + "\n".join(rows) + "\n\n"
        "A question passes when its highest passage score is at or above the cutoff, the rule "
        "`answer_question` applies. This is the score gate only: the API also refuses when "
        "every passage above the cutoff is too large for the context budget, which the harness "
        "doesn't model. Balanced accuracy is the mean of the two shares. A `configured` "
        "cutoff is taken from the settings as given, not tuned on this dataset: "
        "`dense_min_score` for dense similarities and `rerank_min_score` for reranker scores. "
        "A calibrated one was chosen on the `dev` split only. Unreranked `hybrid` has no gate: "
        "its scores are RRF values, which rank passages but aren't comparable to a cutoff."
        + _calibrations(results, calibration)
    )


def _calibrations(results: dict[str, dict], calibration: dict[str, dict]) -> str:
    if not calibration:
        return ""
    rules = {entry["rule"] for entry in calibration.values()}
    shared = len(rules) == 1
    intro = f"\n\nEach calibrated cutoff is {rules.pop()}.\n\n" if shared else "\n\n"
    lines = [_calibrated(results, config, entry, shared) for config, entry in calibration.items()]
    return intro + "\n".join(lines)


def _calibrated(results: dict[str, dict], config: str, entry: dict, shared: bool) -> str:
    dev = entry["dev"]
    rule = "" if shared else f", chosen as {entry['rule']},"
    text = (
        f"- `{config}`: {entry['cutoff']}{rule} with balanced accuracy "
        f"{dev['balanced_accuracy']:.3f} on `dev` ({dev['answerable']} answerable and "
        f"{dev['unanswerable']} unanswerable questions)"
    )
    gate = _summary(results, config).get("evidence_gate")
    if config not in results:
        return text + f"; `{config}` hasn't been run on `test`."
    if not gate or gate.get("cutoff") != entry["cutoff"]:
        return text + f"; the `{config}` run on `test` used another cutoff, so rerun it."
    return text + f" and {gate['balanced_accuracy']:.3f} on `test`."


def _paired(results: dict[str, dict], questions: list[Question]) -> str:
    tested = [q for q in questions if q.split == "test"]
    answerable = [q for q in tested if q.kind != "unanswerable"]
    rows = []
    for first, second in PAIRS:
        label = f"| `{first}` vs `{second}` |"
        if first not in results or second not in results:
            rows.append(f"{label} not run | – | – | – | – | – |")
            continue
        a, b = _rows_by_id(results[first]), _rows_by_id(results[second])
        if any(q.id not in a or q.id not in b for q in tested):
            rows.append(f"{label} different questions; rerun both | – | – | – | – | – |")
            continue
        cells = _disagreements([(_found(q, a[q.id]), _found(q, b[q.id])) for q in answerable])
        cutoffs = [_gate_cutoff(results, first), _gate_cutoff(results, second)]
        if None in cutoffs:
            cells += ["–", "–", "–"]
        else:
            right = [
                (_gate_right(q, a[q.id], cutoffs[0]), _gate_right(q, b[q.id], cutoffs[1]))
                for q in tested
            ]
            cells += _disagreements(right)
        rows.append(f"{label} " + " | ".join(cells) + " |")
    return (
        "## Paired comparison (test split)\n\n"
        "| Comparison | Recall@5: only first | Only second | p | Gate right: only first | "
        "Only second | p |\n|---|---:|---:|---:|---:|---:|---:|\n" + "\n".join(rows) + "\n\n"
        f"Each row compares two configurations on the same {len(answerable)} answerable and "
        f"{len(tested) - len(answerable)} unanswerable `test` questions. The Recall@5 columns "
        "count the answerable questions one configuration finds completely in its top 5 and "
        "the other doesn't. The gate columns count the questions one gate gets right (an "
        "answerable question passes, an unanswerable one is refused) and the other gets "
        "wrong, each at its own cutoff. p is the two-sided exact McNemar test on those "
        "disagreements: the chance of a split at least this uneven if neither configuration "
        "were better. A p above 0.05 means this sample doesn't show a difference, not that "
        "there is none."
    )


def _rows_by_id(result: dict) -> dict[str, dict]:
    return {row["id"]: row for row in result.get("per_question", [])}


def _found(question: Question, row: dict) -> bool:
    ranked = [Ranked(item["path"], tuple(item["headings"])) for item in row["ranked"]]
    return recall_at(5, ranked, question.gold) == 1.0


def _gate_cutoff(results: dict[str, dict], config: str) -> float | None:
    return (_summary(results, config).get("evidence_gate") or {}).get("cutoff")


def _gate_right(question: Question, row: dict, cutoff: float) -> bool:
    passes = row["top_score"] is not None and row["top_score"] >= cutoff
    return passes if question.kind != "unanswerable" else not passes


def _disagreements(pairs: list[tuple[bool, bool]]) -> list[str]:
    only_first = sum(a and not b for a, b in pairs)
    only_second = sum(b and not a for a, b in pairs)
    return [str(only_first), str(only_second), f"{exact_mcnemar(only_first, only_second):.3f}"]


def _latency(results: dict[str, dict]) -> str:
    rows = []
    for config in CONFIGS:
        latency = _summary(results, config).get("latency_ms")
        if config not in results:
            rows.append(f"| {config} | not run | – | – |")
        else:
            device = (results[config].get("settings") or {}).get("embedding_device")
            where = f"`{device}`" if device else "not recorded"
            rows.append(
                f"| {config} | {_ms(latency, 'median')} | {_ms(latency, 'p95')} | {where} |"
            )
    return (
        "## Retrieval latency (test split)\n\n"
        "| Configuration | Median (ms) | p95 (ms) | Embedding device |\n|---|---:|---:|---|\n"
        + "\n".join(rows)
        + "\n\n"
        "Retrieval only, from the question to ranked passages, with the models already "
        "loaded, on the machine that ran `eval.run`, not the production server. Generation "
        "isn't included."
    )


def _answer_review(review: dict | None) -> str:
    heading = "## Answer review (manual sample)\n\n"
    if not review:
        return (
            heading + "No answer review has been made. `uv run python -m eval.answers` asks "
            "the sample, and its reviewer fills `backend/eval/results/answer_review.json`."
        )
    answers = review["answers"]
    rows, totals, named, complete = [], dict.fromkeys(VERDICTS, 0), 0, True
    issues = []
    for answer in answers:
        verdicts = [citation["review"].get("verdict", "") for citation in answer["citations"]]
        names = bool(PASSAGE_NAMED.search(answer.get("answer") or ""))
        named += names
        if not all(verdicts):
            complete = False
            counts = "not reviewed | – | –"
        else:
            counts = " | ".join(str(verdicts.count(verdict)) for verdict in VERDICTS)
            for verdict in verdicts:
                totals[verdict] = totals.get(verdict, 0) + 1
        found = answer.get("issues", [])
        issues += [f"- {answer['id']}: {issue}" for issue in found]
        rows.append(
            f"| {answer['id']} | {answer['outcome']} | {len(verdicts)} | {counts} | "
            f"{len(found)} | {'yes' if names else 'no'} |"
        )
    rule = f", by this rule: {review['rule']}" if review.get("rule") else ""
    settings = review.get("settings") or {}
    models = sorted({answer["model"] for answer in answers if answer.get("model")})
    asked_with = (
        f" They were asked with `{settings['retrieval_mode']}` retrieval, reranking "
        f"{'on' if settings.get('rerank_enabled') else 'off'}, and answered by "
        + ", ".join(f"`{model}`" for model in models)
        + "."
        if settings.get("retrieval_mode") and models
        else ""
    )
    tally = (
        f" Of {sum(totals.values())} citations, {totals['supports']} support the claim they "
        f"are attached to, {totals['partly']} partly support it and "
        f"{totals['does not support']} don't."
        if complete
        else " Some citations aren't reviewed yet."
    )
    listed = (
        "\n\nStatement issues, problems in an answer that per-citation verdicts can miss "
        "(a statement no cited passage states, or a claim with no marker):\n\n" + "\n".join(issues)
        if issues
        else ""
    )
    note = f" {review['note']}" if review.get("note") else ""
    return (
        heading + "| Question | Outcome | Citations | Supports | Partly | Does not support | "
        "Statement issues | Names a passage |\n|---|---|---:|---:|---:|---:|---:|---|\n"
        + "\n".join(rows)
        + listed
        + "\n\n"
        f"A manual sample, not a measurement: {len(answers)} of {len(review['sampled'])} "
        "sampled questions were asked (every eighth answerable `test` question)."
        f"{asked_with} Each citation was read against the section it cites by "
        f"{review.get('reviewer') or 'nobody yet'}{rule}.{tally}{note}\n\n"
        f'{named} of {len(answers)} answers name a passage ("Passage 2", "the first '
        'passage") instead of citing it with a marker, counted by a text pattern. The system '
        "prompt asks the model not to, and this sample was asked with that rule in place. No run "
        "without the prompt rule exists, so this doesn't show whether the rule made the "
        "difference."
    )


def _targets(results: dict[str, dict], reviewed: bool) -> str:
    cells = []
    for config in CONFIGS:
        overall = _summary(results, config).get("overall")
        if config not in results or not overall:
            cells.append("not run")
        elif not reviewed:
            # Until the owner has reviewed the sample, no number counts as a result.
            cells.append(f"provisional ({overall['recall@5']:.3f})")
        else:
            met = "met" if overall["recall@5"] >= RECALL_TARGET else "missed"
            cells.append(f"{met} ({overall['recall@5']:.3f})")
    return (
        "## Plan.md §10.5 targets\n\n"
        "| Target | " + " | ".join(CONFIGS) + " |\n|---|" + "---|" * len(CONFIGS) + "\n"
        f"| Recall@5 ≥ {RECALL_TARGET:.0%} | " + " | ".join(cells) + " |\n\n"
        "A target is called met or missed only once the owner has reviewed the question "
        "sample. "
        f"The query latency target (p95 under {LATENCY_TARGET_MS // 1000} seconds) covers the "
        "whole answer, including generation, so this phase can't report it as met or missed: "
        "the retrieval part is in the latency table above, and end-to-end latency on the "
        "production server is measured in Phase 4. Citation validity, tenant isolation and "
        "ingestion recovery aren't measured by this harness."
    )


def _limits(questions: list[Question], reviewed: bool) -> str:
    answerable = [q for q in questions if q.kind != "unanswerable"]
    exact = sum(q.kind == "exact_term" for q in answerable) / len(answerable) if answerable else 0
    review = (
        "The owner reviewed a sample of them and their gold labels."
        if reviewed
        else "The owner hasn't reviewed a sample of them yet."
    )
    return (
        "## Limits\n\n"
        "- The questions were written by the project's author, who also built the system, so "
        "they may favour it. Gold labels name sections rather than chunks, and "
        f"{exact:.0%} of the answerable questions use exact terms. {review}\n"
        "- The questions were written while reading the corpus's section headings, and each "
        "chunk is embedded with its heading path, so a question that echoes a heading is "
        "easier than a real user's question is likely to be.\n"
        "- A gold label can't name a page's introduction, the text before its first heading: "
        "an entry with no headings covers the whole page. A question whose best answer is an "
        "introduction counts as missed when retrieval returns that introduction.\n"
        "- One corpus: the English Kubernetes concepts pages. Nothing here says how retrieval "
        "does on code, OpenAPI specs or incident reports.\n"
        "- Relevance is judged by section. A chunk in the right section counts even when it "
        "isn't the passage that answers the question.\n"
        "- Latency is from the machine that ran the harness, not the production server."
    )


def _summary(results: dict[str, dict], config: str) -> dict:
    return (results.get(config) or {}).get("summary") or {}


def _num(stats: dict | None, key: str) -> str:
    value = (stats or {}).get(key)
    return "–" if value is None else f"{value:.3f}"


def _ms(stats: dict | None, key: str) -> str:
    value = (stats or {}).get(key)
    return "–" if value is None else f"{value:.0f}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m eval.report", description="Write the Phase 2 evaluation results doc."
    )
    parser.add_argument("--results", type=Path, default=Path("eval/results"))
    parser.add_argument("--questions", type=Path, default=Path("eval/questions.jsonl"))
    parser.add_argument("--review", type=Path, default=Path("eval/review.json"))
    parser.add_argument("--out", type=Path, default=Path("../docs/phase-2-evaluation.md"))
    args = parser.parse_args(argv)

    results = {
        config: json.loads((args.results / f"{config}.json").read_text(encoding="utf-8"))
        for config in CONFIGS
        if (args.results / f"{config}.json").exists()
    }
    reviewed = args.review.exists() and bool(
        json.loads(args.review.read_text(encoding="utf-8")).get("reviewed_on")
    )
    calibration_file = args.results / "calibration.json"
    calibration = (
        json.loads(calibration_file.read_text(encoding="utf-8"))
        if calibration_file.exists()
        else {}
    )
    review_file = args.results / "answer_review.json"
    answer_review = (
        json.loads(review_file.read_text(encoding="utf-8")) if review_file.exists() else None
    )
    text = render(results, load_questions(args.questions), reviewed, calibration, answer_review)
    args.out.write_text(text, encoding="utf-8")
    print(f"Wrote {args.out.as_posix()} ({', '.join(results) or 'no runs'})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
