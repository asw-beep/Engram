"""Build docs/phase-2-evaluation.md from the result files eval.run wrote.

    uv run python -m eval.report

Every number in the document comes from a result file. A configuration without one is
listed as "not run", never estimated (CLAUDE.md, "Evaluation claims").
"""

import argparse
import json
from collections import Counter
from pathlib import Path

from eval.dataset import KINDS, Question, load_questions

CONFIGS = ("dense", "hybrid", "hybrid_rerank")
DESCRIPTIONS = {
    "dense": "BGE-M3 vectors in Qdrant",
    "hybrid": "dense and BM25 (OpenSearch), fused with RRF",
    "hybrid_rerank": "hybrid, then BGE-reranker-v2-m3",
}
RECALL_TARGET = 0.85
LATENCY_TARGET_MS = 5000


def render(results: dict[str, dict], questions: list[Question], reviewed: bool) -> str:
    parts = [_heading(reviewed), _dataset(results, questions), _quality(results)]
    parts += [_by_kind(results, questions), _gate(results), _latency(results)]
    parts += [_targets(results), _limits()]
    return "\n\n".join(parts) + "\n"


def _heading(reviewed: bool) -> str:
    status = (
        "**Status: reviewed.** The owner has reviewed a sample of the questions and their gold "
        "labels (`backend/eval/review.json`)."
        if reviewed
        else "**Status: Provisional.** The owner hasn't reviewed the sample of questions and "
        "gold labels yet, so no number here counts as a result (spec §3)."
    )
    return (
        "# Phase 2 retrieval evaluation\n\n"
        f"{status}\n\n"
        "Generated by `uv run python -m eval.report` from `backend/eval/results/*.json`. "
        "Regenerate it rather than editing it. Each configuration's numbers come from "
        "`uv run python -m eval.run --config <name>`, run from `backend/`."
    )


def _dataset(results: dict[str, dict], questions: list[Question]) -> str:
    counts = Counter((q.kind, q.split) for q in questions)
    rows = [
        f"| {kind} | {counts[kind, 'dev']} | {counts[kind, 'test']} |"
        for kind in KINDS
        if counts[kind, "dev"] or counts[kind, "test"]
    ]
    corpus = next((r["corpus"] for r in results.values() if "corpus" in r), None)
    corpus_line = (
        f"The corpus held {corpus['documents']} current documents and {corpus['chunks']} chunks "
        "when the first listed run was made."
        if corpus
        else "No run has been made, so the corpus size isn't recorded."
    )
    return (
        "## Dataset\n\n"
        f"{len(questions)} questions, written for this project by its author from the corpus "
        "and not collected from real users. `backend/eval/README.md` describes the corpus, "
        "its commit, how the questions were written and the split rule. Tuning uses the `dev` "
        "split only; every number below is from the `test` split.\n\n"
        "| Kind | dev | test |\n|---|---:|---:|\n" + "\n".join(rows) + f"\n\n{corpus_line}"
    )


def _quality(results: dict[str, dict]) -> str:
    rows = []
    for config in CONFIGS:
        overall = _summary(results, config).get("overall")
        if config not in results:
            rows.append(f"| {config} | not run | – | – | – |")
        else:
            metrics = ("recall@5", "recall@10", "mrr@10", "ndcg@10")
            rows.append(f"| {config} | " + " | ".join(_num(overall, m) for m in metrics) + " |")
    legend = "\n".join(f"- `{c}`: {DESCRIPTIONS[c]}" for c in CONFIGS)
    return (
        "## Retrieval quality (test split, answerable questions)\n\n"
        "| Configuration | Recall@5 | Recall@10 | MRR@10 | NDCG@10 |\n"
        "|---|---:|---:|---:|---:|\n" + "\n".join(rows) + "\n\n" + legend + "\n\n"
        "A chunk is relevant when it comes from a gold document and its heading path starts "
        "with a gold section's. Recall@K counts a question only when every gold section has a "
        "chunk in the top K, so a `multi_section` question needs both. NDCG is graded: the "
        "first chunk from each gold section earns 2 and the first chunk from elsewhere in a "
        "gold document earns 1, so a ranking holding only the gold sections scores below 1 "
        "when the rest of a gold document could also have been found."
    )


def _by_kind(results: dict[str, dict], questions: list[Question]) -> str:
    tested = Counter(q.kind for q in questions if q.split == "test" and q.kind != "unanswerable")
    rows = []
    for kind in KINDS:
        if not tested[kind]:
            continue
        cells = []
        for config in CONFIGS:
            stats = (_summary(results, config).get("by_kind") or {}).get(kind)
            if config not in results:
                cells.append("not run")
            else:
                cells.append(f"{_num(stats, 'recall@5')} / {_num(stats, 'mrr@10')}")
        rows.append(f"| {kind} | {tested[kind]} | " + " | ".join(cells) + " |")
    return (
        "## By question kind (test split, Recall@5 / MRR@10)\n\n"
        "| Kind | Questions | "
        + " | ".join(CONFIGS)
        + " |\n|---|---:|---|---|---|\n"
        + "\n".join(rows)
    )


def _gate(results: dict[str, dict]) -> str:
    rows = []
    for config in CONFIGS:
        gate = _summary(results, config).get("evidence_gate")
        if config not in results:
            rows.append(f"| {config} | not run | – | – | – |")
        else:
            cells = [
                _num(gate, key) for key in ("cutoff", "answerable_passed", "unanswerable_refused")
            ]
            rows.append(
                f"| {config} | " + " | ".join(cells) + f" | {_num(gate, 'balanced_accuracy')} |"
            )
    return (
        "## Evidence gate (test split)\n\n"
        "| Configuration | Cutoff | Answerable passed | Unanswerable refused | "
        "Balanced accuracy |\n|---|---:|---:|---:|---:|\n" + "\n".join(rows) + "\n\n"
        "A question passes when its highest passage score is at or above the cutoff, the rule "
        "`answer_question` applies. Balanced accuracy is the mean of the two shares. Cutoffs "
        "are chosen on the `dev` split only."
    )


def _latency(results: dict[str, dict]) -> str:
    rows = []
    for config in CONFIGS:
        latency = _summary(results, config).get("latency_ms")
        if config not in results:
            rows.append(f"| {config} | not run | – |")
        else:
            rows.append(f"| {config} | {_ms(latency, 'median')} | {_ms(latency, 'p95')} |")
    return (
        "## Retrieval latency (test split)\n\n"
        "| Configuration | Median (ms) | p95 (ms) |\n|---|---:|---:|\n" + "\n".join(rows) + "\n\n"
        "Retrieval only, from the question to ranked passages, with the models already "
        "loaded, on the development laptop's GPU. Generation isn't included."
    )


def _targets(results: dict[str, dict]) -> str:
    cells = []
    for config in CONFIGS:
        overall = _summary(results, config).get("overall")
        if config not in results or not overall:
            cells.append("not run")
        else:
            met = "met" if overall["recall@5"] >= RECALL_TARGET else "missed"
            cells.append(f"{met} ({overall['recall@5']:.3f})")
    return (
        "## Plan.md §10.5 targets\n\n"
        "| Target | " + " | ".join(CONFIGS) + " |\n|---|---|---|---|\n"
        f"| Recall@5 ≥ {RECALL_TARGET:.0%} | " + " | ".join(cells) + " |\n\n"
        f"The query latency target (p95 under {LATENCY_TARGET_MS // 1000} seconds) covers the "
        "whole answer, including generation, so this phase can't report it as met or missed: "
        "the retrieval part is in the latency table above, and end-to-end latency on the "
        "production server is measured in Phase 4. Citation validity, tenant isolation and "
        "ingestion recovery aren't measured by this harness."
    )


def _limits() -> str:
    return (
        "## Limits\n\n"
        "- The questions were written by the project's author, who also built the system, so "
        "they may favour it. Gold labels name sections rather than chunks, a third of the "
        "questions use exact terms, and the owner reviews a sample.\n"
        "- One corpus: the English Kubernetes concepts pages. Nothing here says how retrieval "
        "does on code, OpenAPI specs or incident reports.\n"
        "- Relevance is judged by section. A chunk in the right section counts even when it "
        "isn't the passage that answers the question.\n"
        "- Latency is from a laptop GPU, not the production server."
    )


def _summary(results: dict[str, dict], config: str) -> dict:
    return (results.get(config) or {}).get("summary") or {}


def _num(stats: dict | None, key: str) -> str:
    value = (stats or {}).get(key)
    return "–" if value is None else f"{value:.3f}"


def _ms(stats: dict | None, key: str) -> str:
    value = (stats or {}).get(key)
    return "–" if value is None else f"{value:.0f}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m eval.report", description="Write the Phase 2 evaluation results doc."
    )
    parser.add_argument("--results", type=Path, default=Path("eval/results"))
    parser.add_argument("--questions", type=Path, default=Path("eval/questions.jsonl"))
    parser.add_argument("--review", type=Path, default=Path("eval/review.json"))
    parser.add_argument("--out", type=Path, default=Path("../docs/phase-2-evaluation.md"))
    args = parser.parse_args(argv)

    results = {
        config: json.loads((args.results / f"{config}.json").read_text(encoding="utf-8"))
        for config in CONFIGS
        if (args.results / f"{config}.json").exists()
    }
    reviewed = args.review.exists() and bool(
        json.loads(args.review.read_text(encoding="utf-8")).get("reviewed_on")
    )
    text = render(results, load_questions(args.questions), reviewed)
    args.out.write_text(text, encoding="utf-8")
    print(f"Wrote {args.out.as_posix()} ({', '.join(results) or 'no runs'})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
